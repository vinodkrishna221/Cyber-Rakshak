export const ALL_CATEGORIES = Object.values(CATEGORY_DEFINITIONS);

export function getCategoryDefinition(category: ComplaintCategory): CategoryDefinition {
  return CATEGORY_DEFINITIONS[category] || CATEGORY_DEFINITIONS.other_cybercrime;
}

export function getSubCategoryDefinition(
  subCategoryKey: ComplaintSubCategory,
): SubCategoryDefinition | undefined {
  for (const cat of ALL_CATEGORIES) {
    const found = cat.subCategories.find((sub) => sub.key === subCategoryKey);
    if (found) return found;
  }
  return undefined;
}

export function getSubCategoriesByCategory(
  category: ComplaintCategory,
): SubCategoryDefinition[] {
  return CATEGORY_DEFINITIONS[category]?.subCategories || [];
}
